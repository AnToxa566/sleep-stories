import baseConfig from "../../eslint.config.mjs";

// Which folders of src/app each folder may import from (README.md, "Dependencies"). The
// direction is one way, so the folders cannot form a cycle.
const allowedImports = {
    platform: ["platform"],
    providers: ["providers", "platform"],
    listens: ["listens", "platform"],
    generation: ["generation", "providers", "platform"],
    topics: ["topics", "listens", "generation", "providers", "platform"],
    queue: ["queue", "topics", "listens", "generation", "providers", "platform"],
    preferences: ["preferences", "queue", "providers", "platform"],
    internal: ["internal", "queue", "generation", "providers", "platform"]
};
const folders = Object.keys(allowedImports);

// A relative path that goes up and then names a folder of src/app. It relies on no inner
// folder being called like one of them (README.md, "Dependencies").
const folderBoundaries = Object.entries(allowedImports).map(([folder, allowed]) => {
    const forbidden = folders.filter((other) => !allowed.includes(other));
    return {
        files: [`**/src/app/${folder}/**/*.ts`],
        // Specs wire several folders together on purpose.
        ignores: ["**/*.spec.ts", "**/*.int-spec.ts"],
        rules: {
            "no-restricted-imports": [
                "error",
                {
                    patterns: [
                        {
                            regex: `^(\\.\\./)+(${forbidden.join("|")})(/|$)`,
                            message: `${folder} may import only from: ${allowed.join(", ")} (see apps/api/README.md, "Dependencies")`
                        }
                    ]
                }
            ]
        }
    };
});

export default [
    ...baseConfig,
    {
        // Generated by `prisma generate`; never linted or hand-edited.
        ignores: ["src/generated/**"]
    },
    ...folderBoundaries
];
