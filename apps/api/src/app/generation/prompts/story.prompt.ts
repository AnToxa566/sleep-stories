export interface StoryPromptInput {
  style: StoryStyle;
  // A catalogue-model title, or text a person typed: untrusted.
  topicTitle: string;
}

export function buildStoryUserMessage(input: StoryPromptInput): string {
  return `<style>
${input.style}
</style>

<topic>
${cleanValue(input.topicTitle)}
</topic>

Напиши историю.`;
}
